use std::{fs, path::Path};

#[test]
fn display_folder_and_storage_status_commands_require_local_main_and_the_captured_workspace_view() {
    let commands = include_str!("../../../src-tauri/src/commands/mod.rs");
    let build = include_str!("../../../src-tauri/build.rs");
    let handlers = include_str!("../../../src-tauri/src/lib.rs");
    let base = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../src-tauri");
    for (command, core_method) in [
        ("choose_display_folder", "select_display_path_if_current"),
        ("set_display_folder", "select_display_folder_if_current"),
        ("get_document_storage_hold", "document_storage_hold"),
    ] {
        let body = commands
            .split(&format!("pub async fn {command}("))
            .nth(1)
            .unwrap()
            .split("#[tauri::command]")
            .next()
            .unwrap();
        assert!(body.contains("webview.label() != \"main\""));
        assert!(body.contains("workspace_id: String"));
        assert!(body.contains("view_id: String"));
        let compact: String = body.split_whitespace().collect();
        assert!(compact.contains(&format!("core.{core_method}(&workspace_id,&view_id,")));
        assert!(!body.contains("core.select("));
        if command == "choose_display_folder" {
            assert!(compact.contains("core.select_display_path_if_current(&workspace_id,&view_id,snapshot.display_revision,"));
        }
        if command == "set_display_folder" {
            assert!(body.contains("expected_display_revision: u64"));
            assert!(compact.contains("core.select_display_folder_if_current(&workspace_id,&view_id,expected_display_revision,"));
        }
        if command == "get_document_storage_hold" {
            assert!(body.contains("tab_id: String"));
            assert!(body.contains("request_id: u64"));
            assert!(compact.contains("&tab_id,request_id"));
        }
        assert!(build.contains(&format!("\"{command}\",")));
        assert!(handlers.contains(&format!("commands::{command},")));

        let identifier = format!("allow-{}", command.replace('_', "-"));
        let permission = fs::read_to_string(
            base.join("permissions/autogenerated")
                .join(format!("{command}.toml")),
        )
        .unwrap();
        assert!(permission.contains(&format!("commands.allow = [\"{command}\"]")));
        assert!(permission.contains(&format!("commands.deny = [\"{command}\"]")));
        let mut grants = 0;
        for file in fs::read_dir(base.join("capabilities")).unwrap() {
            let path = file.unwrap().path();
            if path.extension().is_none_or(|extension| extension != "json") {
                continue;
            }
            let value: serde_json::Value =
                serde_json::from_slice(&fs::read(path).unwrap()).unwrap();
            for permission in value["permissions"].as_array().unwrap() {
                if permission
                    .as_str()
                    .or_else(|| permission["identifier"].as_str())
                    != Some(identifier.as_str())
                {
                    continue;
                }
                grants += 1;
                assert_eq!(value["identifier"], "main");
                assert_eq!(value["local"], true);
                assert_eq!(value["webviews"], serde_json::json!(["main"]));
                assert!(value.get("remote").is_none());
            }
        }
        assert_eq!(grants, 1);
    }
}

