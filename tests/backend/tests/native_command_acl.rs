#[test]
fn artifact_export_is_a_local_main_only_command_with_no_document_filesystem_capability() {
    let build = include_str!("../../../src-tauri/build.rs");
    assert!(build.contains("\"save_html_artifact\","));
    let permission =
        include_str!("../../../src-tauri/permissions/autogenerated/save_html_artifact.toml");
    assert!(permission.contains("commands.allow = [\"save_html_artifact\"]"));
    assert!(permission.contains("commands.deny = [\"save_html_artifact\"]"));
    let capabilities = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../src-tauri/capabilities");
    let mut grants = 0;
    for file in fs::read_dir(capabilities).unwrap() {
        let file = file.unwrap().path();
        if file.extension().is_none_or(|extension| extension != "json") {
            continue;
        }
        let value: serde_json::Value = serde_json::from_slice(&fs::read(file).unwrap()).unwrap();
        if value["permissions"]
            .as_array()
            .unwrap()
            .iter()
            .any(|permission| permission.as_str() == Some("allow-save-html-artifact"))
        {
            grants += 1;
            assert_eq!(value["identifier"], "main");
            assert_eq!(value["local"], true);
            assert_eq!(value["webviews"], serde_json::json!(["main"]));
            assert!(value.get("remote").is_none());
        }
    }
    assert_eq!(grants, 1);
    let command = include_str!("../../../src-tauri/src/commands/artifact.rs");
    assert!(command.contains("webview.label() != \"main\""));
    assert!(command.contains("app.path().download_dir()"));
    assert!(command.contains("dialog.save_file("));
    assert!(!command.contains("request.path"));
    assert!(!command.contains("create_dir"));
    let viewer = include_str!("../../../src/features/document-viewer/DocumentViewer.tsx");
    assert!(viewer.contains("sandbox=\"allow-scripts\""));
    assert!(!viewer.contains("allow-downloads"));
    let lib = include_str!("../../../src-tauri/src/lib.rs");
    assert!(lib.contains("commands::artifact::save_html_artifact,"));
    assert!(lib.contains(".on_download(|_, _| false)"));
}
